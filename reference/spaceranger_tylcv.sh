#!/usr/bin/env bash
# spaceranger_tylcv.sh - re-run Space Ranger with TYLCV added to your tomato reference.
#
#   bash spaceranger_tylcv.sh check       # 1. verify inputs; changes nothing
#   bash spaceranger_tylcv.sh reference   # 2. build the merged reference (spaceranger mkref)
#   bash spaceranger_tylcv.sh commands    # 3. write rerun_counts.sh from your original runs' _cmdline files
#
# Edit the five settings below first.
set -euo pipefail

TOMATO_REF="/path/to/original_spaceranger_reference"   # folder holding fasta/genome.fa and genes/genes.gtf(.gz)
TYLCV_DIR="tylcv_ref"                                    # output folder of make_tylcv_reference.py
OLD_RUNS=(                                               # your 8 original `spaceranger count` output folders
  /path/to/run_A1_TYLCV_7dpi
  /path/to/run_A2_TYLCV_7dpi
)
NEW_REF_NAME="SL_TYLCV"                                  # folder name of the merged reference
OUT_DIR="tylcv_reruns"                                   # where the new runs will be written
THREADS=16
MEMGB=64

die()  { echo "ERROR: $*" >&2; exit 1; }
ok()   { echo "  ok  $*"; }

tomato_gtf() { ls "$TOMATO_REF"/genes/genes.gtf* 2>/dev/null | head -1 || true; }

check() {
  echo "== Checking inputs"
  command -v spaceranger >/dev/null || die "spaceranger not on PATH"
  ok "$(spaceranger --version 2>&1 | head -1)"
  [[ -s "$TOMATO_REF/fasta/genome.fa" ]] || die "missing $TOMATO_REF/fasta/genome.fa"
  [[ -n "$(tomato_gtf)" ]] || die "missing $TOMATO_REF/genes/genes.gtf(.gz)"
  ok "tomato reference: $TOMATO_REF"
  for f in TYLCV_IL.fa tylcv_spaceranger.gtf tylcv_reference_report.txt; do
    [[ -s "$TYLCV_DIR/$f" ]] || die "missing $TYLCV_DIR/$f (run make_tylcv_reference.py first)"
  done
  local n L end
  n=$(grep -c '^>' "$TYLCV_DIR/TYLCV_IL.fa")
  [[ "$n" == 1 ]] || die "TYLCV_IL.fa must hold exactly one record (found $n)"
  grep -q '^>TYLCV\([[:space:]]\|$\)' "$TYLCV_DIR/TYLCV_IL.fa" || die "TYLCV_IL.fa record must be named TYLCV"
  L=$(grep -v '^>' "$TYLCV_DIR/TYLCV_IL.fa" | tr -d '\n\r ' | wc -c)
  end=$(awk -F'\t' '$1=="TYLCV"{print $5; exit}' "$TYLCV_DIR/tylcv_spaceranger.gtf")
  [[ "$end" == "$L" ]] || die "GTF end ($end) differs from FASTA length ($L)"
  ok "TYLCV: one record, $L nt, GTF matches"
  grep -E '^(accession|length|orientation):' "$TYLCV_DIR/tylcv_reference_report.txt" | sed 's/^/      /'
  local clash; clash=$(gzip -dcf "$TOMATO_REF/fasta/genome.fa" | grep -c '^>TYLCV\([[:space:]]\|$\)' || true)
  [[ "${clash:-0}" == 0 ]] || die "the tomato FASTA already contains a contig named TYLCV"
  ok "no contig-name clash"
  for r in "${OLD_RUNS[@]}"; do
    [[ -d "$r" ]] || { echo "  !!  $r not found"; continue; }
    local v="?"; [[ -f "$r/_versions" ]] && v=$(grep -o '"spaceranger": *"[^"]*"' "$r/_versions" | sed 's/.*: *"//; s/"$//' || true)
    [[ -f "$r/_cmdline" ]] && ok "$(basename "$r"): _cmdline found, made with $v" || echo "  !!  $(basename "$r"): no _cmdline (write its command by hand)"
  done
}

reference() {
  check
  echo "== Building merged FASTA and GTF"
  mkdir -p merged_inputs
  { gzip -dcf "$TOMATO_REF/fasta/genome.fa"; echo; cat "$TYLCV_DIR/TYLCV_IL.fa"; } | awk 'NF' > merged_inputs/genome.fa
  { gzip -dcf "$(tomato_gtf)"; cat "$TYLCV_DIR/tylcv_spaceranger.gtf"; } > merged_inputs/genes.gtf
  ok "contigs: $(grep -c '^>' merged_inputs/genome.fa) (tomato + TYLCV); GTF lines: $(grep -vc '^#' merged_inputs/genes.gtf)"
  echo "== spaceranger mkref (can take an hour or more)"
  spaceranger mkref --genome="$NEW_REF_NAME" --fasta=merged_inputs/genome.fa \
                    --genes=merged_inputs/genes.gtf --nthreads="$THREADS" --memgb="$MEMGB"
  local g; g=$(ls "$NEW_REF_NAME"/genes/genes.gtf* | head -1)
  [[ $(gzip -dcf "$g" | grep -c '^TYLCV') == 2 ]] || die "TYLCV features missing from $g"
  ok "merged reference ready: $(cd "$NEW_REF_NAME" && pwd)"
}

commands() {
  [[ -d "$NEW_REF_NAME" ]] || die "build the reference first: bash $0 reference"
  local ref_abs out="rerun_counts.sh" major
  ref_abs=$(cd "$NEW_REF_NAME" && pwd)
  major=$(spaceranger --version 2>&1 | grep -o '[0-9]\+\.[0-9]\+' | head -1 | cut -d. -f1 || true)
  { echo "#!/usr/bin/env bash"; echo "# Re-runs generated by spaceranger_tylcv.sh: original arguments, new --id and --transcriptome."
    echo "set -euo pipefail"; echo "mkdir -p $OUT_DIR && cd $OUT_DIR"; } > "$out"
  for r in "${OLD_RUNS[@]}"; do
    if [[ ! -f "$r/_cmdline" ]]; then echo "# TODO $(basename "$r"): no _cmdline, add its command by hand" >> "$out"; continue; fi
    local cmd; cmd=$(tr '\n' ' ' < "$r/_cmdline" | sed -E \
      -e "s#--transcriptome[= ]+[^ ]+#--transcriptome=$ref_abs#" \
      -e 's#--id[= ]+([^ ]+)#--id=\1_tylcv#')
    if [[ "${major:-0}" -ge 3 && "$cmd" != *"--create-bam"* ]]; then cmd="$cmd --create-bam=true"; fi
    echo "$cmd" >> "$out"
  done
  chmod +x "$out"
  echo "== Wrote $out:"; sed 's/^/   /' "$out"
  echo "Check each line (FASTQs, --image, --slide, --area, --loupe-alignment must be the originals),"
  echo "then run it, or submit each 'spaceranger count' line as its own cluster job."
}

case "${1:-}" in
  check) check ;;
  reference) reference ;;
  commands) commands ;;
  *) echo "usage: bash $0 check|reference|commands"; exit 1 ;;
esac
